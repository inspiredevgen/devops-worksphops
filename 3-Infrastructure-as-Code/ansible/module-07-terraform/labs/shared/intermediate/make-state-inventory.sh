#!/usr/bin/env bash
# =============================================================================
# EN: Write inventory/lab.terraform_state.yml for this lab folder. The terraform_state plugin runs Terraform in a
#     TEMPORARY directory, so the state path must be ABSOLUTE: this script computes it.
#       ../../shared/intermediate/make-state-inventory.sh aws|azure [terraform|tofu]
# FR : Écrit inventory/lab.terraform_state.yml pour ce dossier de lab. Le plugin terraform_state lance Terraform dans
#     un dossier TEMPORAIRE : le chemin de l'état doit donc être ABSOLU ; ce script le calcule.
# =============================================================================
set -euo pipefail
CLOUD="${1:?usage: make-state-inventory.sh aws|azure [terraform|tofu]}"
BINARY="${2:-terraform}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STATE="$(cd "$HERE/../../../../lab-hosts/$CLOUD" && pwd)/terraform.tfstate"
mkdir -p inventory

case "$CLOUD" in
  aws)
    COMPOSE='  ansible_host: public_ip
  ansible_user: "'"'"'ec2-user'"'"' if tags.OS == '"'"'al2023'"'"' else '"'"'ubuntu'"'"'"
  cloud: "'"'"'aws'"'"'"
  cloud_instance_id: id' ;;
  azure)
    COMPOSE='  ansible_host: public_ip_address
  ansible_user: "'"'"'azureuser'"'"'"
  cloud: "'"'"'azure'"'"'"
  cloud_vm_name: name' ;;
  *) echo "aws or azure" >&2; exit 2 ;;
esac

cat > inventory/lab.terraform_state.yml <<YAML
---
# EN: Generated by make-state-inventory.sh: hosts read from the Terraform STATE of lab-hosts/$CLOUD (no cloud API call).
# FR : Généré par make-state-inventory.sh : hôtes lus dans l'ÉTAT Terraform de lab-hosts/$CLOUD (aucun appel d'API cloud).
plugin: cloud.terraform.terraform_state
binary_path: $BINARY
backend_type: local
backend_config:
  path: $STATE
hostnames:
  - tag:Host
compose:
$COMPOSE
keyed_groups:
  - key: tags.Role
    prefix: role
  - key: tags.Environment
    prefix: env
  - key: tags.OS
    prefix: os
YAML
echo "✅ inventory/lab.terraform_state.yml → $STATE"
