#!/bin/bash
# File: scripts/web/bootstrap.sh
# Purpose : Turn a fresh Amazon Linux 2023 instance into a web server of the Auto Scaling group:
#           1. identity (IMDSv2)                 2. Node.js 22 + CloudWatch agent
#           3. app files + 'npm ci' (lock file)  4. Amazon RDS CA bundle
#           5. config (NO password: the app reads Secrets Manager) + systemd service 'labapp'
#           6. CloudWatch Logs shipping          7. self-tests
# Run     : by user-data.sh at first boot (as root). Can be re-run by hand: sudo bash bootstrap.sh
# Options : SECRET_ID=lab7/app/db  APP_VERSION=1.0.0  PORT=8080  LOG_GROUP=/lab7/app
#           BASE_URL=<raw GitHub URL of scripts/web>
# Logs    : /var/log/cloud-init-output.log (this script) · /var/log/labapp/app.log (the app)
set -euo pipefail

[[ $EUID -eq 0 ]] || { echo "Please run as root (sudo)."; exit 1; }
export HOME="${HOME:-/root}"   # cloud-init may run user data without HOME; npm needs it for its cache
SECRET_ID="${SECRET_ID:-lab7/app/db}"
APP_VERSION="${APP_VERSION:-1.0.0}"
PORT="${PORT:-8080}"
LOG_GROUP="${LOG_GROUP:-/lab7/app}"
BASE_URL="${BASE_URL:-https://raw.githubusercontent.com/inspiredevgen/devops-worksphops/refs/heads/main/2-Cloud-Infrastructure/aws-lab-rds-node-asg/scripts/web}"

SRC="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
APP_DIR=/opt/labapp
ENV_FILE=/etc/labapp/labapp.env
LOG_DIR=/var/log/labapp

log() { echo -e "\n==> [$(date +%T)] $*"; }

# ---------------------------------------------------------------------------
log "1/7 Instance identity (IMDSv2)"
TOKEN=$(curl -sf --noproxy '*' -m 2 -X PUT http://169.254.169.254/latest/api/token -H "X-aws-ec2-metadata-token-ttl-seconds: 300" || true)
md() { curl -sf --noproxy '*' -m 2 -H "X-aws-ec2-metadata-token: $TOKEN" "http://169.254.169.254/latest/meta-data/$1" || echo "n/a"; }
INSTANCE_ID=$(md instance-id); AZ=$(md placement/availability-zone)
REGION=$(md placement/region)
[[ "$REGION" =~ ^[a-z]{2}(-[a-z]+)+-[0-9]$ ]] || REGION="${AWS_REGION:-us-west-1}"
echo "Instance ${INSTANCE_ID} in ${AZ} (${REGION}), app version ${APP_VERSION}, secret ${SECRET_ID}"

# ---------------------------------------------------------------------------
log "2/7 Installing Node.js 22 and the CloudWatch agent"
if dnf -y -q install nodejs22 nodejs22-npm >/dev/null 2>&1; then
  NODE_BIN=/usr/bin/node-22; NPM_BIN=/usr/bin/npm-22
else
  echo "nodejs22 not available, falling back to nodejs20"
  dnf -y -q install nodejs20 nodejs20-npm; NODE_BIN=/usr/bin/node-20; NPM_BIN=/usr/bin/npm-20
fi
dnf -y -q install amazon-cloudwatch-agent nmap-ncat >/dev/null
echo "Node.js $("$NODE_BIN" --version) · npm $("$NPM_BIN" --version)"

# ---------------------------------------------------------------------------
log "3/7 Application files + dependencies from the lock file (npm ci)"
id labapp >/dev/null 2>&1 || useradd --system --home-dir "$APP_DIR" --shell /sbin/nologin labapp
mkdir -p "$APP_DIR/views" "$LOG_DIR"
for f in server.js package.json package-lock.json views/page.js; do
  if [[ -f "$SRC/app/$f" ]]; then
    cp "$SRC/app/$f" "$APP_DIR/$f"; echo "  copied     app/$f"
  else
    curl -fsSL --retry 5 --retry-delay 3 --retry-all-errors -o "$APP_DIR/$f" "${BASE_URL}/app/${f}"
    echo "  downloaded app/$f"
  fi
done
# npm ci = exact versions from package-lock.json, every instance identical (no surprise upgrades)
( cd "$APP_DIR" && "$NPM_BIN" ci --omit=dev --no-audit --no-fund --loglevel=error )
( cd "$APP_DIR" && "$NPM_BIN" ls --omit=dev --depth=0 | sed 's/^/  /' )

# ---------------------------------------------------------------------------
log "4/7 Amazon RDS CA bundle (for direct connections to RDS; RDS Proxy uses an Amazon Root CA)"
curl -fsSL --retry 5 --retry-all-errors https://truststore.pki.rds.amazonaws.com/global/global-bundle.pem -o "$APP_DIR/rds-ca.pem"
chown -R root:labapp "$APP_DIR"
chmod -R u=rwX,g=rX,o= "$APP_DIR"
chown labapp:labapp "$LOG_DIR"; chmod 750 "$LOG_DIR"

# ---------------------------------------------------------------------------
log "5/7 Configuration (no password here) and systemd service"
mkdir -p /etc/labapp
cat > "$ENV_FILE" <<EOF
# Generated by bootstrap.sh - contains NO credentials: the app reads them from Secrets Manager
NODE_ENV=production
AWS_REGION=${REGION}
SECRET_ID=${SECRET_ID}
APP_VERSION=${APP_VERSION}
PORT=${PORT}
DB_SSL_CA=${APP_DIR}/rds-ca.pem
EOF
chmod 644 "$ENV_FILE"

cat > /etc/systemd/system/labapp.service <<EOF
[Unit]
Description=Pacific Learning student registry (Node.js ${APP_VERSION})
After=network-online.target
Wants=network-online.target

[Service]
User=labapp
Group=labapp
WorkingDirectory=${APP_DIR}
EnvironmentFile=${ENV_FILE}
ExecStart=${NODE_BIN} server.js
StandardOutput=append:${LOG_DIR}/app.log
StandardError=append:${LOG_DIR}/app.log
Restart=always
RestartSec=3
# Graceful shutdown: SIGTERM -> the app finishes in-flight requests (max 25 s)
KillSignal=SIGTERM
TimeoutStopSec=30
NoNewPrivileges=true
ProtectSystem=full
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
cat > /etc/logrotate.d/labapp <<EOF
${LOG_DIR}/app.log {
  daily
  rotate 3
  compress
  missingok
  copytruncate
}
EOF
systemctl daemon-reload
systemctl enable labapp >/dev/null 2>&1
systemctl restart labapp

# ---------------------------------------------------------------------------
log "6/7 CloudWatch agent: ship ${LOG_DIR}/app.log to log group ${LOG_GROUP}"
cat > /opt/aws/amazon-cloudwatch-agent/etc/amazon-cloudwatch-agent.json <<EOF
{
  "agent": { "run_as_user": "root" },
  "logs": {
    "logs_collected": {
      "files": {
        "collect_list": [
          { "file_path": "${LOG_DIR}/app.log", "log_group_name": "${LOG_GROUP}",
            "log_stream_name": "{instance_id}", "retention_in_days": 7 },
          { "file_path": "/var/log/cloud-init-output.log", "log_group_name": "${LOG_GROUP}-bootstrap",
            "log_stream_name": "{instance_id}", "retention_in_days": 7 }
        ]
      }
    }
  }
}
EOF
/opt/aws/amazon-cloudwatch-agent/bin/amazon-cloudwatch-agent-ctl -a fetch-config -m ec2 -s \
  -c file:/opt/aws/amazon-cloudwatch-agent/etc/amazon-cloudwatch-agent.json >/dev/null \
  && echo "  CloudWatch agent running" || echo "  WARN CloudWatch agent did not start (check the role's logs permissions)"

# ---------------------------------------------------------------------------
log "7/7 Self-tests"
systemctl is-active --quiet labapp && echo "  OK   service labapp is running" || echo "  FAIL service labapp: journalctl -u labapp -n 50 ; tail ${LOG_DIR}/app.log"
for _ in $(seq 1 20); do
  code=$(curl -s -o /tmp/labapp-ready.json -w '%{http_code}' "http://localhost:${PORT}/health?strict=1" || true)
  [[ "$code" == "200" ]] && break
  sleep 3
done
if [[ "$code" == "200" ]]; then
  echo "  OK   readiness 200: $(cat /tmp/labapp-ready.json)"
else
  echo "  WARN readiness ${code}: $(cat /tmp/labapp-ready.json 2>/dev/null)"
  echo "       The ALB still sends traffic (liveness /health = 200) - fix the database path, no reboot needed."
fi
rm -f /tmp/labapp-ready.json
echo
echo "==> Bootstrap finished on ${INSTANCE_ID} (${AZ}), version ${APP_VERSION}."
