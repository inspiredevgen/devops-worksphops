#!/bin/bash
# File: scripts/web/web-setup.sh
# Purpose : Install the Python (Flask) student registry on ONE web server (Amazon Linux 2023):
#           Python + virtual environment, pinned packages, Amazon RDS CA bundle (TLS),
#           systemd service 'labapp' (gunicorn on port 8080, non-root user), self-tests.
#           Run it on lab6-web-a AND lab6-web-b.
# Run     : sudo DB_HOST=<RDS_ENDPOINT> DB_PASSWORD='<APPUSER_PASSWORD>' bash web-setup.sh
# Options : APP_VERSION=1.0.0   BASE_URL=<raw GitHub URL of scripts/web>   PORT=8080
set -euo pipefail

[[ $EUID -eq 0 ]] || { echo "Please run with sudo."; exit 1; }
: "${DB_HOST:?Set DB_HOST to the RDS endpoint name (RDS -> Databases -> lab6-mysql -> Endpoint)}"
: "${DB_PASSWORD:?Set DB_PASSWORD to the appuser password printed by rds-init.sh (in single quotes)}"
DB_PORT="${DB_PORT:-3306}"
DB_NAME="${DB_NAME:-labapp}"
DB_USER="${DB_USER:-appuser}"
PORT="${PORT:-8080}"
APP_VERSION="${APP_VERSION:-1.0.0}"
BASE_URL="${BASE_URL:-https://raw.githubusercontent.com/inspiredevgen/devops-worksphops/refs/heads/main/2-Cloud-Infrastructure/aws-lab-rds-python-alb/scripts/web}"

SRC="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
APP_DIR="/opt/labapp"
ENV_FILE="/etc/labapp/labapp.env"

log() { echo -e "\n\033[1;34m==> $*\033[0m"; }
if [[ "$DB_HOST" =~ ^[0-9.]+$ ]]; then
  echo "DB_HOST must be the RDS endpoint NAME, not an IP address: TLS verifies the name in the certificate."; exit 1
fi

# ---------------------------------------------------------------------------
log "1/6 Instance identity (IMDSv2)"
TOKEN=$(curl -sf --noproxy '*' -m 2 -X PUT http://169.254.169.254/latest/api/token -H "X-aws-ec2-metadata-token-ttl-seconds: 120" || true)
md() { curl -sf --noproxy '*' -m 2 -H "X-aws-ec2-metadata-token: $TOKEN" "http://169.254.169.254/latest/meta-data/$1" || echo "n/a"; }
echo "Instance $(md instance-id) in $(md placement/availability-zone), private IP $(md local-ipv4)"

# ---------------------------------------------------------------------------
log "2/6 Installing Python (newest available: 3.12, 3.11, else the default python3) and tools"
PY=""
for v in 3.12 3.11; do
  if dnf -y -q install "python${v}" "python${v}-pip" >/dev/null 2>&1; then PY="python${v}"; break; fi
done
if [[ -z "$PY" ]]; then dnf -y -q install python3 python3-pip; PY="python3"; fi
dnf -y -q install nmap-ncat >/dev/null 2>&1 || true
echo "Using $($PY --version)"

# ---------------------------------------------------------------------------
log "3/6 Getting the application files and installing pinned packages"
id labapp >/dev/null 2>&1 || useradd --system --home-dir "$APP_DIR" --shell /sbin/nologin labapp
mkdir -p "$APP_DIR/templates"
for f in app.py requirements.txt templates/index.html; do
  if [[ -f "$SRC/$f" ]]; then
    cp "$SRC/$f" "$APP_DIR/$f"; echo "  copied     $f"
  else
    curl -fsSL --retry 3 -o "$APP_DIR/$f" "${BASE_URL}/${f}"; echo "  downloaded $f"
  fi
done
"$PY" -m venv "$APP_DIR/venv"
"$APP_DIR/venv/bin/pip" install -q --upgrade pip
"$APP_DIR/venv/bin/pip" install -q -r "$APP_DIR/requirements.txt"
"$APP_DIR/venv/bin/pip" freeze | sed 's/^/  /'

# ---------------------------------------------------------------------------
log "4/6 Downloading the Amazon RDS CA bundle (TLS + server identity check)"
curl -fsSL --retry 3 https://truststore.pki.rds.amazonaws.com/global/global-bundle.pem -o "$APP_DIR/rds-ca.pem"
chown -R root:labapp "$APP_DIR"
chmod -R u=rwX,g=rX,o= "$APP_DIR"

# ---------------------------------------------------------------------------
log "5/6 Writing the configuration (root-only) and the systemd service"
mkdir -p /etc/labapp
( umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by web-setup.sh - readable by root only (systemd reads it before dropping privileges)
DB_HOST=${DB_HOST}
DB_PORT=${DB_PORT}
DB_NAME=${DB_NAME}
DB_USER=${DB_USER}
DB_PASSWORD='${DB_PASSWORD}'
DB_SSL_CA=${APP_DIR}/rds-ca.pem
APP_VERSION=${APP_VERSION}
EOF
)
cat > /etc/systemd/system/labapp.service <<EOF
[Unit]
Description=Pacific Learning student registry (Flask + gunicorn)
After=network-online.target
Wants=network-online.target

[Service]
User=labapp
Group=labapp
WorkingDirectory=${APP_DIR}
EnvironmentFile=${ENV_FILE}
ExecStart=${APP_DIR}/venv/bin/gunicorn --workers 2 --bind 0.0.0.0:${PORT} --access-logfile - --forwarded-allow-ips="*" app:app
Restart=always
RestartSec=3
NoNewPrivileges=true
ProtectSystem=full
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable --now labapp
systemctl restart labapp
sleep 3

# ---------------------------------------------------------------------------
log "6/6 Self-tests"
if nc -z -w 3 "$DB_HOST" "$DB_PORT"; then
  echo "  OK   TCP ${DB_HOST}:${DB_PORT} reachable (lab6-rds-sg allows lab6-web-sg)"
else
  echo "  FAIL TCP ${DB_HOST}:${DB_PORT}: check lab6-rds-sg inbound 3306 from lab6-web-sg"
fi
systemctl is-active --quiet labapp && echo "  OK   service labapp is running" || { echo "  FAIL service labapp: journalctl -u labapp -n 50"; }
echo "  Readiness (/health?strict=1):"
curl -s "http://localhost:${PORT}/health?strict=1" | sed 's/^/    /' || true
echo
echo "==> Done on $(md instance-id). The ALB marks it healthy after 2 successful checks on /health (port ${PORT})."
